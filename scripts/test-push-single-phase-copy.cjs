const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('supabase/functions/send-push/index.ts', 'utf8');
const code = source.slice(source.indexOf('const compactPushText ='), source.indexOf('const normalizePhoneDigits ='));
const context = vm.createContext({});
vm.runInContext(ts.transpile(code + '\nglobalThis.build = buildCompactAppointmentPushBody;', {target: ts.ScriptTarget.ES2022}), context);
const phase = {phase:'initial',label:'Taglio Uomo + Shampoo',startAt:'2026-09-15T09:30:00',endAt:'2026-09-15T10:00:00',operatorName:'Alex'};
const body = (phases, event='appointment_rescheduled_by_salon') => context.build({payload:{event_type:event,appointmentDate:'2026-09-15',appointmentTime:'09:30',bookingTimeline:'timeline',bookingTimelineItems:[{phases}]}},'client');
assert.equal(body([phase]), '15/09/26 ore 9:30 con Alex\nTaglio Uomo + Shampoo 09:30–10:00');
assert.ok(!body([phase], 'appointment_reorganized_by_salon').includes('ª fase'));
const pause={...phase,phase:'processing',durationMinutes:20};
assert.ok(body([phase,pause]).includes('Posa · 20 min'));
assert.ok(!body([phase,pause]).includes('ª fase'));
const multi=body([phase,pause,{...phase,phase:'final',label:'Piega',operatorName:'Sara'}]);
assert.ok(multi.includes('1ª fase · Taglio Uomo + Shampoo'));
assert.ok(multi.includes('2ª fase · Piega'));
assert.ok(multi.includes('con Sara'));
console.log('PASS: single combo without phase label, multi-phase numbering and processing/operator details preserved');
