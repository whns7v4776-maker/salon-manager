const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const migrationPath = path.resolve(
  __dirname,
  '../supabase/migrations/20260831234500_set_public_booking_window_atomically.sql',
);
const sql = fs.readFileSync(migrationPath, 'utf8');

const functionMatch = sql.match(
  /create or replace function public\.set_public_booking_window_v1\([\s\S]*?\)\s*returns jsonb[\s\S]*?as \$\$([\s\S]*?)\$\$;/i,
);
assert.ok(functionMatch, 'Missing set_public_booking_window_v1 RPC definition.');
const body = functionMatch[1];

assert.match(
  sql,
  /security definer\s+set search_path = public, pg_temp/i,
  'The RPC must be SECURITY DEFINER with a fixed search_path.',
);
assert.match(body, /if auth\.uid\(\) is null then/i, 'Missing auth guard.');
assert.match(
  body,
  /v_workspace_id\s*:=\s*public\.current_workspace_id\(\)/i,
  'Workspace must come from the authenticated session.',
);
assert.match(
  body,
  /v_workspace_id is null or not public\.workspace_access_allowed\(\)/i,
  'Missing workspace access guard.',
);

assert.match(
  body,
  /from public\.client_portals[\s\S]*?where[\s\S]*?workspace_id\s*=\s*v_workspace_id[\s\S]*?for update/i,
  'The authoritative client_portals row must be locked before mutation.',
);
assert.match(
  body,
  /v_unit not in \('days', 'weeks', 'months', 'years'\)[\s\S]*?v_unit\s*:=\s*'days'/i,
  'Invalid units must normalize to days.',
);
for (const [unit, maximum] of [
  ['weeks', 104],
  ['months', 24],
  ['years', 2],
  ['else', 730],
]) {
  assert.match(
    body,
    new RegExp(`${unit === 'else' ? 'else' : `when '${unit}' then`}\\s+${maximum}`, 'i'),
    `Missing ${unit} booking-window maximum ${maximum}.`,
  );
}
assert.match(body, /greatest\(\s*1,/i, 'Booking-window value must clamp to 1.');

assert.match(
  body,
  /v_server_updated_at\s*:=\s*clock_timestamp\(\)/i,
  'The authoritative timestamp must be generated by PostgreSQL.',
);
for (const key of [
  'publicBookingWindowValue',
  'publicBookingWindowUnit',
  'publicBookingWindowUpdatedAt',
]) {
  assert.match(body, new RegExp(`'${key}'`), `Missing canonical key ${key}.`);
}
assert.match(
  body,
  /update public\.client_portals[\s\S]*?availability_settings\s*=\s*v_canonical_settings/i,
  'The portal must receive the canonical settings object.',
);
assert.match(
  body,
  /update public\.owner_app_snapshots[\s\S]*?\|\|\s*v_window_patch[\s\S]*?where snapshot\.workspace_id\s*=\s*v_workspace_id/i,
  'An existing owner snapshot must receive the same three-key patch.',
);
assert.doesNotMatch(
  body,
  /insert\s+into\s+public\.owner_app_snapshots/i,
  'The RPC must not create an owner snapshot.',
);
assert.match(
  body,
  /'availabilitySettings',\s*v_canonical_settings/i,
  'The response must return the canonical availabilitySettings payload.',
);

assert.match(
  sql,
  /revoke all on function public\.set_public_booking_window_v1\(integer, text\)[\s\S]*?from public, anon, service_role/i,
  'PUBLIC, anon, and service_role must not execute the RPC.',
);
assert.match(
  sql,
  /grant execute on function public\.set_public_booking_window_v1\(integer, text\)[\s\S]*?to authenticated/i,
  'Only authenticated must receive execute permission.',
);

const migrationOutsideFunction = sql.replace(functionMatch[0], '');
assert.doesNotMatch(
  migrationOutsideFunction,
  /\b(?:insert\s+into|update|delete\s+from|truncate)\s+public\.(?:client_portals|owner_app_snapshots|workspaces)\b/i,
  'The migration must not mutate account data while installing the RPC.',
);

console.log('Contratto RPC atomica finestra prenotazioni verificato.');
