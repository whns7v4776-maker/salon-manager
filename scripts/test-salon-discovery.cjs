 assert.equal((await db.query(`select * from search_public_salons('')`)).rows.length,0);
 assert.equal((await db.query(`select * from search_public_salons('%')`)).rows.length,0);
 const nearby = (await db.query(`select * from search_public_salons('',40.85,14.26)`)).rows;
 assert.equal(nearby[0].salon_code,'salon-0'); assert.ok(nearby[0].distance_km<0.01); assert.ok(nearby[1].distance_km>100);
 assert.deepEqual(Object.keys(nearby[0]).sort(),['salon_code','salon_name','address','city','photo_url','image_kind','distance_km'].sort());
 await assert.rejects(db.query('select * from salon_directory_profiles'));
 await assert.rejects(db.query(`select * from search_public_salons('',999,14)`));
 await db.exec(`reset role; set app.workspace = '${ids[0]}'; set role authenticated;`);
 assert.equal((await db.query('select * from salon_directory_profiles')).rows.length,1);
 await db.query('insert into storage.objects(bucket_id,name) values($1,$2)', ['salon-directory', `${ids[0]}/image.jpg`]);
