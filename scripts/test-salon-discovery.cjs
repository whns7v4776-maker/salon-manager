 const foreign = await db.query('update salon_directory_profiles set enabled=false where workspace_id=$1 returning workspace_id',[ids[1]]); assert.equal(foreign.rows.length,0);
 await db.query('update salon_directory_profiles set enabled=false where workspace_id=$1',[ids[0]]);
 await db.exec('set role anon');
 assert.equal((await db.query(`select * from search_public_salons('Salone 0')`)).rows.length,0);
 await db.exec('reset role');
 await db.query('update salon_directory_profiles set latitude=null,longitude=null where workspace_id=$1',[ids[1]]);
 assert.equal((await db.query("select * from search_public_salons('',40.85,14.26)")).rows.length,0);
 assert.equal((await db.query("select * from search_public_salons('Salone 1')")).rows.length,1);
 await assert.rejects(db.query('update salon_directory_profiles set enabled=true,address_confirmed=false where workspace_id=$1',[ids[0]]));
 await db.exec(fs.readFileSync('supabase/migrations/20260917183000_default_public_salon_discovery.sql','utf8'));
 await db.exec("insert into workspaces(id,slug,salon_name,street_line,city,subscription_status) values('00000000-0000-4000-8000-000000000005','new-salon','Morph Hair Lab','Via Test 1','Monte Compatri','active')");
 await db.exec('set role anon');
 assert.equal((await db.query("select * from search_public_salons('Morph')")).rows.length,1);
 assert.equal((await db.query("select * from search_public_salons('Monte Compatri')")).rows.length,1);
