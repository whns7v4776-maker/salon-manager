const fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript'),assert=require('node:assert/strict');
const source=fs.readFileSync('app/cliente-screen.tsx','utf8');
const start=source.indexOf('  const isDayDisabled = useCallback(');
const end=source.indexOf('\n  );',start)+6;
let full=true,closed=false,current=true;
const context={useCallback:f=>f,canChooseDay:true,today:'2026-09-19',availabilitySettings:{},getDateAvailabilityInfo:()=>({closed}),isDayFullForService:()=>full,isDayAuthorityCurrent:()=>current};
vm.createContext(context);
vm.runInContext(ts.transpile(source.slice(start,end)+'\nglobalThis.disabled = isDayDisabled;'),context);
assert.equal(context.disabled('2026-09-20'),false,'full day opens for waitlist');
full=null;assert.equal(context.disabled('2026-09-20'),true,'pending authority remains blocked');
full=true;closed=true;assert.equal(context.disabled('2026-09-20'),true,'closed salon remains blocked');
closed=false;assert.equal(context.disabled('2026-09-18'),true,'past day remains blocked');
current=false;assert.equal(context.disabled('2026-09-20'),true,'stale authority remains blocked');
const targetStart=source.indexOf('  const dayWaitlistTargetSlotTimes = useMemo(');
const targetEnd=source.indexOf('\n  );',targetStart)+6;
const targetCtx={useMemo:f=>f(),waitlistSlotBlocks:[{slotTimes:['09:00','09:15']},{slotTimes:['09:15','09:30']}]};
vm.createContext(targetCtx);
vm.runInContext(ts.transpile(source.slice(targetStart,targetEnd)+'\nglobalThis.times=dayWaitlistTargetSlotTimes;'),targetCtx);
assert.equal(JSON.stringify(targetCtx.times),JSON.stringify(['09:00','09:15','09:30']),'whole-day alert covers all starts, not just first of each block');
console.log('PASS: full-day access, closed/past/loading guards, complete daily waitlist coverage');
