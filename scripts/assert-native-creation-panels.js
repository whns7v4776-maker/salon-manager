const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('app/(tabs)/servizi.tsx', 'utf8');
const boundary = source.slice(source.indexOf('const AppOnlyFastExpansionBoundary ='), source.indexOf('// Keep creation-tab'));
assert.match(boundary, /Platform.OS !== 'web' && nativeTitle/);
assert.match(boundary, /<Modal visible=\{nativeExpanded\}[^>]*onRequestClose=\{close\}/);
assert.match(boundary, /<GestureHandlerRootView/);
assert.match(boundary, /<CreationSheet[\s\S]*?onClose=\{close\}/);
const sheet=fs.readFileSync('components/creation-sheet.tsx','utf8');
assert.match(sheet, /keyboardShouldPersistTaps="handled"/);
assert.match(sheet, /scrollResponderScrollNativeHandleToKeyboard|scroll\.scrollTo/);
assert.match(boundary, /\{nativeOverlays\}/);
assert.doesNotMatch(boundary, /setDisableParentSwipe|resetForm|resetOperatoreForm/);
assert.match(boundary, /if \(Platform.OS === 'web'\) \{\s*onWebToggle\(\)/);
assert.match(source, /nativeTitle="Aggiungi servizio"/);
assert.match(source, /nativeTitle="Aggiungi operatore"/);
assert.match(source, /nativeCreationPanel === 'service' \? renderCreationOverlays\(\) : null/);
assert.match(source, /nativeCreationPanel === 'operator' \? renderCreationOverlays\(\) : null/);
assert.match(source, /draftStore=\{Platform.OS !== 'web' \? compositionDraftRef : undefined\}/);
assert.match(source, /savedMode=\{Platform.OS !== 'web' \? creationModeRef : undefined\}/);
console.log('Native creation panels, web isolation and draft retention checks passed.');
