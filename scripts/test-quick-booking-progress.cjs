const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('src/lib/quick-booking-progress.ts','utf8');
const testExports = {};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports: testExports});
const step = testExports.quickBookingUnlockedStep;
const draft = {mode:false,customer:false,service:false,operatorRequired:true,operator:false};
assert.equal(step(1,draft),1);
draft.mode=true; assert.equal(step(1,draft),2);
draft.customer=true; assert.equal(step(2,draft),3);
draft.service=true; assert.equal(step(3,draft),4);
draft.operator=true; assert.equal(step(4,draft),5);
assert.equal(step(5,{...draft,customer:false,service:false,operator:false}),5,'Editing a completed draft must not relock controls');
assert.equal(step(3,{...draft,customer:false,service:false}),3,'Previously reached services remain editable');
assert.equal(step(1,{...draft,customer:false}),2,'Preset operator/service cannot bypass customer selection');
assert.equal(step(3,{...draft,operator:false,operatorRequired:false}),5,'Services without operators may proceed to time');
assert.equal(step(5,{...draft,mode:false}),1,'A fresh draft resets progress');
console.log('Quick booking progressive unlock: 9 checks passed');
