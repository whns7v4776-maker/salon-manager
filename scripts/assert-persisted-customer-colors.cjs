const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require(process.argv[2] || '@electric-sql/pglite');
const workspace = '00000000-0000-0000-0000-000000000001';
const owner = '00000000-0000-0000-0000-000000000002';
const other = '00000000-0000-0000-0000-000000000003';
(async () => {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table workspaces(id uuid primary key);
    create table customers(id uuid primary key,workspace_id uuid,created_at timestamptz default now(),email text,phone text);
    create table workspace_members(workspace_id uuid,user_id uuid,role text);
    insert into workspaces values('${workspace}'),('${other}');
    insert into workspace_members values('${workspace}','${owner}','owner');
    insert into customers select md5(i::text)::uuid,'${workspace}',now(),null,null from generate_series(1,80)i;
    select set_config('request.jwt.claim.sub','${owner}',false);`);
  const before = await db.query('select * from customers order by id');
  await db.exec(fs.readFileSync('supabase/migrations/20260906133000_persist_customer_identity_colors.sql','utf8'));
  const preserved = await db.query('select * from customer_identity_colors');
  const read = async () => (await db.query(`select * from get_owner_customer_identity_colors('${workspace}') order by customer_id`)).rows;
  const first = await read();
  assert.equal(first.length, 80);
  assert.equal(new Set(first.map(x => x.color)).size, 80, 'No duplicate colors, even without email or phone');
  for (const row of preserved.rows) assert.equal(first.find(x => x.customer_id === row.customer_id).color, row.color);
  assert.deepEqual(await read(), first, 'Repeat allocation must not recolor');
  assert.deepEqual((await db.query('select * from customers order by id')).rows, before.rows, 'No customer data changed');
  await db.exec(`insert into customers values(md5('new')::uuid,'${workspace}',now(),null,null)`);
  const expanded = await read();
  for (const row of first) assert.deepEqual(expanded.find(x => x.customer_id===row.customer_id), row);
  await assert.rejects(() => db.query(`select * from get_owner_customer_identity_colors('${other}')`), /access denied/i);
  await db.exec('set role anon');
  await assert.rejects(() => db.query('select * from customer_identity_colors'), /permission denied/i);
  await assert.rejects(() => db.query(`select * from get_owner_customer_identity_colors('${workspace}')`), /permission denied/i);
  await db.exec('reset role');
  await db.exec(`insert into workspace_members values('${other}','${owner}','owner');
    insert into customers select md5('other'||i)::uuid,'${other}',now() + i * interval '1 second',null,null from generate_series(1,6)i`);
  const priority = await db.query(`select x.color from get_owner_customer_identity_colors('${other}') x join customers c on c.id=x.customer_id order by c.created_at`);
  assert.deepEqual(priority.rows.map(x=>x.color), ['#EAB308','#F97316','#EF4444','#2563EB','#8B5CF6','#EC4899']);
  const snapshot = await read();
  await db.exec(`delete from customers where id=md5('new')::uuid`);
  const deleted = await read();
  for (const row of deleted) assert.deepEqual(row, snapshot.find(x=>x.customer_id===row.customer_id));
  await db.close();
  console.log('PASS persisted colors: unique, null contacts, legacy preservation, stable reload, new/delete, owner isolation, anonymous denial, vivid priority');
})().catch(error => { console.error(error); process.exitCode = 1; });
