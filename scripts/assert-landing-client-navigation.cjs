const fs = require('fs');
const vm = require('vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
const s = fs.readFileSync('app/index.tsx','utf8');
const ast = ts.createSourceFile('index.tsx', s, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const nodes=[]; (function walk(node){nodes.push(node);ts.forEachChild(node,walk)})(ast);
const navigateNode=nodes.find(node=>ts.isVariableDeclaration(node)&&node.name.getText(ast)==='navigateToHref');
assert.ok(navigateNode, 'Use the actual navigation initializer');
const calls = [];
const active = {current:false};
const context = {useCallback: fn=>fn, clientLandingActiveRef:active, Platform:{OS:'ios'}, router:{replace:x=>calls.push(x),push:x=>calls.push(x)}};
vm.createContext(context);
vm.runInContext(ts.transpile(`const ${navigateNode.getText(ast)};\nglobalThis.navigate = navigateToHref;`),context);
const destination = {pathname:'/cliente',params:{autologin:'1',email:'previous@example.com'}};
context.navigate(destination);
context.navigate('/cliente-scanner');
assert.equal(calls.length,0,'owner form must block hidden client navigation');
active.current=true;
context.navigate(destination);
assert.equal(calls.length,1,'explicit client flow remains available');
active.current=false;
context.navigate(destination);
assert.equal(calls.length,1,'late completion must not reopen client');
context.navigate('/privacy');
assert.equal(calls.length,2,'public navigation remains available');
console.log('PASS: iOS owner/client navigation isolation and late completion');

// Execute the actual effect through dev cleanup/setup replay, then audience changes.
const effect=nodes.find(node=>ts.isCallExpression(node)&&node.expression.getText(ast)==='useEffect'&&node.arguments[0]?.getText(ast).includes('clientLandingActiveRef.current = showClientLanding'));
assert.ok(effect, 'Use the actual client lifecycle effect');
let setup;
const lifecycle = {clientLandingActiveRef: active, showClientLanding: true, audiencePickerOpen:false, useEffect: fn => { setup = fn; }};
vm.createContext(lifecycle);
vm.runInContext(ts.transpile(effect.getText(ast)), lifecycle);
let cleanup = setup();
assert.equal(active.current, true);
cleanup();
assert.equal(active.current, false);
cleanup = setup();
assert.equal(active.current, true, 'dev effect replay must restore client access without another render');
cleanup();
lifecycle.showClientLanding = false;
cleanup = setup();
assert.equal(active.current, false, 'owner audience must still block client access');
cleanup();
console.log('PASS: client access guard survives dev effect replay and blocks owner/unmounted flow');

lifecycle.showClientLanding = true; lifecycle.audiencePickerOpen = true;
cleanup = setup();
assert.equal(active.current, false, 'chooser keeps hidden client navigation disabled');
cleanup();
console.log('PASS: chooser keeps the client navigation guard disabled');
